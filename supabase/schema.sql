-- profil: lihat milik sendiri (admin: semua); ubah hanya display_name milik sendiri
revoke all on public.profiles from anon, authenticated;
grant select on public.profiles to authenticated;
grant update (display_name) on public.profiles to authenticated;
create policy profiles_select on public.profiles for select to authenticated
  using (id = auth.uid() or public.is_admin());
create policy profiles_update_own on public.profiles for update to authenticated
  using (id = auth.uid()) with check (id = auth.uid());

-- area & ruangan: dibaca siapa saja, diubah admin
revoke insert, update, delete on public.areas, public.rooms, public.entries from anon;
create policy areas_read  on public.areas for select using (true);
create policy areas_admin on public.areas for all to authenticated
  using (public.is_admin()) with check (public.is_admin());
create policy rooms_read  on public.rooms for select using (true);
create policy rooms_admin on public.rooms for all to authenticated
  using (public.is_admin()) with check (public.is_admin());

