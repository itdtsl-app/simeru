-- ---------------------------------------------------------------------
-- 4. Fungsi buat jadwal (satu/banyak ruangan, berulang, lewati bentrok)
-- ---------------------------------------------------------------------
create or replace function public.create_booking(
  p_room_ids       bigint[],
  p_start          timestamptz,
  p_end            timestamptz,
  p_name           text,
  p_description    text    default null,
  p_type           text    default 'I',
  p_color          text    default null,
  p_tentative      boolean default false,
  p_repeat         text    default 'none',   -- none | daily | weekly | monthly | yearly
  p_repeat_until   date    default null,     -- tanggal lokal, inklusif
  p_skip_conflicts boolean default false,
  p_tz             text    default 'Asia/Jakarta'
) returns jsonb
language plpgsql
as $$
declare
  c_max_occurrences constant int := 400;
  v_series    uuid := case when p_repeat <> 'none' then gen_random_uuid() else null end;
  v_start_l   timestamp := p_start at time zone p_tz;
  v_end_l     timestamp := p_end   at time zone p_tz;
  v_interval  interval;
  v_i         int := 0;
  v_j         int;
  v_s         timestamptz;
  v_e         timestamptz;
  v_starts    timestamptz[] := '{}';
  v_ends      timestamptz[] := '{}';
  v_room      bigint;
  v_c         record;
  v_conf      jsonb := '[]'::jsonb;
  v_created   int := 0;
  v_type      text := upper(left(coalesce(p_type, 'I'), 1));
begin
  if coalesce(trim(p_name), '') = '' then raise exception 'Deskripsi singkat wajib diisi'; end if;
  if p_end <= p_start then raise exception 'Waktu selesai harus setelah waktu mulai'; end if;
  if p_room_ids is null or cardinality(p_room_ids) = 0 then raise exception 'Pilih minimal satu ruangan'; end if;
  if v_type not in ('I', 'E') then v_type := 'I'; end if;
  if p_repeat not in ('none', 'daily', 'weekly', 'monthly', 'yearly') then
    raise exception 'Jenis pengulangan tidak dikenal';
  end if;

  -- 1) daftar kemunculan (occurrence)
  if p_repeat = 'none' then
    v_starts := array[p_start];
    v_ends   := array[p_end];
  else
    if p_repeat_until is null then raise exception 'Tanggal akhir pengulangan wajib diisi'; end if;
    v_interval := case p_repeat
      when 'daily'   then interval '1 day'
      when 'weekly'  then interval '1 week'
      when 'monthly' then interval '1 month'
      else interval '1 year' end;
    loop
      exit when (v_start_l + v_i * v_interval)::date > p_repeat_until;
      v_s := (v_start_l + v_i * v_interval) at time zone p_tz;
      v_e := (v_end_l   + v_i * v_interval) at time zone p_tz;
      v_starts := v_starts || v_s;
      v_ends   := v_ends   || v_e;
      v_i := v_i + 1;
      if v_i > c_max_occurrences then
        raise exception 'Terlalu banyak pengulangan (maksimal % kali)', c_max_occurrences;
      end if;
    end loop;
    if cardinality(v_starts) = 0 then raise exception 'Tanggal akhir pengulangan sebelum tanggal mulai'; end if;
  end if;

  -- 2) cek bentrok untuk semua kombinasi ruangan x kemunculan
  foreach v_room in array p_room_ids loop
    for v_j in 1 .. cardinality(v_starts) loop
      select e.name as ename, r.name as rname into v_c
        from public.entries e join public.rooms r on r.id = e.room_id
       where e.room_id = v_room
         and tstzrange(e.start_time, e.end_time, '[)') && tstzrange(v_starts[v_j], v_ends[v_j], '[)')
       limit 1;
      if found then
        v_conf := v_conf || jsonb_build_object('room_id', v_room, 'room', v_c.rname,
                                               'start', v_starts[v_j], 'with', v_c.ename);
      end if;
    end loop;
  end loop;

  if jsonb_array_length(v_conf) > 0 and not p_skip_conflicts then
    return jsonb_build_object('created', 0, 'conflicts', v_conf);
  end if;

  -- 3) simpan (yang bentrok dilewati bila p_skip_conflicts)
  foreach v_room in array p_room_ids loop
    for v_j in 1 .. cardinality(v_starts) loop
      begin
        insert into public.entries
          (room_id, start_time, end_time, name, description, type, color, tentative, series_id)
        values
          (v_room, v_starts[v_j], v_ends[v_j], trim(p_name), nullif(p_description, ''),
           v_type, nullif(p_color, ''), coalesce(p_tentative, false), v_series);
        v_created := v_created + 1;
      exception when exclusion_violation then
        if not p_skip_conflicts then raise; end if;
      end;
    end loop;
  end loop;

  return jsonb_build_object('created', v_created, 'skipped', v_conf, 'series_id', v_series);
end $$;

grant execute on function public.create_booking(bigint[], timestamptz, timestamptz, text, text, text, text,
                                                boolean, text, date, boolean, text) to authenticated;

