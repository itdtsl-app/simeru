create extension if not exists btree_gist;

-- ---------------------------------------------------------------------
-- 1. Profil pengguna (terhubung ke Supabase Auth)
-- ---------------------------------------------------------------------
create table public.profiles (
  id           uuid primary key references auth.users (id) on delete cascade,
  display_name text,
  role         text not null default 'user' check (role in ('user', 'admin')),
  created_at   timestamptz not null default now()
);

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, display_name)
  values (new.id,
          coalesce(nullif(new.raw_user_meta_data ->> 'display_name', ''),
                   split_part(new.email, '@', 1)));
  return new;
end $$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role = 'admin');
$$;

-- ---------------------------------------------------------------------
-- 2. Area, ruangan, dan jadwal (entries)
-- ---------------------------------------------------------------------
create table public.areas (
  id           bigint generated by default as identity primary key,
  name         text not null,
  sort_order   int  not null default 0,
  start_hour   smallint not null default 7  check (start_hour between 0 and 23),
  end_hour     smallint not null default 19 check (end_hour between 1 and 24),  -- batas bawah grid (eksklusif)
  slot_minutes smallint not null default 30 check (slot_minutes in (5, 10, 15, 20, 30, 60)),
  disabled     boolean  not null default false,
  constraint areas_hours check (end_hour > start_hour)
);

create table public.rooms (
  id          bigint generated by default as identity primary key,
  area_id     bigint not null references public.areas (id) on delete cascade,
  name        text   not null,
  sort_order  int    not null default 0,
  capacity    int,
  description text,
  disabled    boolean not null default false
);
create index rooms_area_idx on public.rooms (area_id);

create table public.entries (
  id              bigint generated by default as identity primary key,
  room_id         bigint      not null references public.rooms (id) on delete cascade,
  start_time      timestamptz not null,
  end_time        timestamptz not null,
  name            text        not null,
  description     text,
  type            char(1)     not null default 'I' check (type in ('I', 'E')),   -- I = Internal, E = External
  color           text check (color is null or color ~ '^#[0-9a-fA-F]{6}$'),     -- null = warna bawaan tipe
  tentative       boolean     not null default false,
  series_id       uuid,                                                          -- jadwal berulang berbagi series_id
  created_by      uuid default auth.uid() references auth.users (id) on delete set null,
  created_by_name text,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),
  constraint entries_time_order check (end_time > start_time),
  -- DUA JADWAL TIDAK BOLEH BERTABRAKAN DI RUANGAN YANG SAMA (dijaga database, bukan hanya aplikasi)
  constraint entries_no_overlap
    exclude using gist (room_id with =, tstzrange(start_time, end_time, '[)') with &&)
);
create index entries_start_idx  on public.entries (start_time);
create index entries_series_idx on public.entries (series_id) where series_id is not null;

create or replace function public.entries_before_write()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'INSERT' then
    if new.created_by is null then new.created_by := auth.uid(); end if;
    if new.created_by_name is null and new.created_by is not null then
      select display_name into new.created_by_name from public.profiles where id = new.created_by;
    end if;
  else
    new.updated_at := now();
    -- pembuat tidak boleh diubah lewat update biasa
    new.created_by := old.created_by;
    new.created_by_name := old.created_by_name;
  end if;
  return new;
end $$;

create trigger entries_before_write
  before insert or update on public.entries
  for each row execute function public.entries_before_write();

-- View praktis (nama ruangan + area), dipakai daftar acara dan feed
create or replace view public.events with (security_invoker = true) as
  select e.*, r.name as room_name, r.area_id, a.name as area_name
    from public.entries e
    join public.rooms r on r.id = e.room_id
    join public.areas a on a.id = r.area_id
   where not r.disabled and not a.disabled;

